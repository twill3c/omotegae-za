import Link from "next/link";
import { CLAIMED_ACTORS, PLAYS } from "@/lib/site";

export const metadata = { title: "方法 — 面替え座" };

export default function Method() {
  const trag = PLAYS.filter((p) => p.genre === "悲劇");
  const com = PLAYS.filter((p) => p.genre === "喜劇");
  const fit = (ps: typeof PLAYS, m: string) => ps.filter((p) => p.chi[m] <= CLAIMED_ACTORS).length;
  const over = trag.filter((p) => p.chi.A_loose > CLAIMED_ACTORS);

  return (
    <main className="wrap narrow" style={{ paddingTop: "2rem" }}>
      <h1>方法</h1>
      <p className="lede">
        測ったこと、測れなかったこと、そして<b>事前に立てた予測が落ちた経緯</b>を記す。
      </p>

      <h2>素材</h2>
      <p>
        <a href="https://github.com/PerseusDL/canonical-greekLit">Perseus Digital Library</a> の
        ギリシア語 TEI XML。四大劇作家の現存全 45 篇(アイスキュロス 7・ソポクレス 8・
        エウリピデス 19・アリストパネス 11)で、<b>62,097 行・17,290 発話</b>。
        英訳ではなく<b>原文</b>を測っている。
      </p>
      <div className="note note--warn">
        <strong>最大の交絡: 校訂者が作家と一対一で対応している。</strong>
        アイスキュロス=Smyth(1922/26)、ソポクレス=Storr(1912/13)、
        エウリピデス=Murray(1902/13)、アリストパネス=Hall &amp; Geldart(1906/07)。
        したがって<b>マークアップ由来の作家間の差は、校訂者間の差と原理的に分離できない</b>。
        たとえば行分割(antilabe)の印はアイスキュロス 2 件に対しアリストパネス 3,468 件だが、
        これはアイスキュロスが行分割を避けた証拠には<b>ならない</b>。
        本サイトが χ を導くのに使うのは<b>話者の系列</b>と<b>合唱隊の発話位置</b>で、
        ここは写本の伝統と劇の構造に縛られており、校訂実務の裁量が比較的効きにくい。
      </div>

      <h2>場面の切り方</h2>
      <p>
        本文に退場は書かれていない。ト書きは近代の編者の補いである。
        そこで<b>合唱隊の歌が登退場を許す</b>という上演上の性質を使って境界を置いた。
      </p>
      <ul>
        <li>
          <b>緩</b> — 合唱隊の発話 1 件で切る。場面は細かくなり、衝突は減り、χ は小さく出る
        </li>
        <li>
          <b>厳</b> — 合唱隊だけで構成される <code>div</code> でのみ切る。場面は大きくなり、
          衝突は増え、χ は大きく出る。<b>こちらが反証側</b>である
        </li>
      </ul>
      <h3>行数の閾値を置かなかった理由</h3>
      <p>
        当初は「一定行数以上の合唱隊単独発話で切る」つもりだった。やめた。
        合唱隊 2,763 発話の長さの分布に<b>谷が無い</b>(1 行 747 / 2 行 512 / 3 行 240 と単調に減衰、
        中央値 3)。合唱隊長の短い受けと本格的な合唱歌を分ける自然な閾値をデータが与えない。
        閾値を自分で決めれば、その値は結果を見て動かせてしまう。
      </p>
      <p>
        <code>div/@subtype</code> の語彙で決める案も潰れた。<b>56 種あり、校訂者ごとにばらける</b>
        (<code>episode</code>/<code>Episode</code>、<code>choral</code>/<code>Choral</code>、
        <code>epirrheme</code>/<code>Epirrheme</code>/<code>epirrhema</code>)。
        <code>@rend</code> に至っては アイスキュロス 0.1% / ソポクレス 0.0% /
        エウリピデス 25.5% / アリストパネス 11.8% で、韻文種別の手がかりにならない。
      </p>
      <p>
        そこで<b>語彙を判定に使わない</b>ことにした。<code>div</code> の境界だけを編者から借り、
        「その区間で語るのが合唱隊だけか」は話者の分類から決める。
        その結果、境界に選ばれた <code>div</code> は <code>strophe</code> 372 /{" "}
        <code>antistrophe</code> 367 / <code>lyric</code> 51 / <code>epode</code> 38 と
        合唱歌の語彙に集中した —— <b>語彙を一切見ずに合唱歌を拾えている</b>ことの裏づけである。
      </p>

      <h2>χ の求め方</h2>
      <p>
        貪欲彩色・近似は使っていない。k を下限から 1 ずつ上げて k 彩色可能性を判定する厳密解で、
        <b>Python と TypeScript で問いの立て方から変えた二実装</b>(片方は「k で足りるか」を判定し、
        もう片方は集合分割を直接最小化する)が 180 組すべてで一致した。
        <b>悲劇 34 篇は集合分割の全列挙(総当たり)でも裏づけてある。</b>
      </p>
      <p>
        計算経路に定数 3 は現れない。「三で足りるか」という問いをコードに埋め込むと、
        答えを先に書いたことになるからである。この不在は Python の構文木と
        TypeScript の字句走査で機械的に検査している。
      </p>

      <h2>落ちた予測</h2>
      <p>
        測る前に「悲劇 34 篇のうち χ ≤ 3 が 31 篇以上、厳・緩の両方で」と登録した。
      </p>
      <div className="note note--warn">
        <strong>不通過。</strong>厳 {fit(trag, "A_strict")}/{trag.length}、緩{" "}
        {fit(trag, "A_loose")}/{trag.length}。
      </div>
      <p>それでも構造は明瞭に出た(緩)。</p>
      <ul>
        <li>
          <b>アリストパネス {fit(com, "A_loose") === 0 ? com.length : com.length - fit(com, "A_loose")}/{com.length} が χ &gt; 3</b> —— 事前登録の予測どおり
        </li>
        <li>
          <b>エウリピデス 19 篇中 17 篇がちょうど χ = 3</b>
        </li>
        <li>
          <b>アイスキュロスの 3 篇がちょうど χ = 2</b> —— 二俳優期の通説と合う
        </li>
      </ul>
      <p>
        そして χ ≥ 4 の悲劇 {over.length} 篇は、<b>すべて同じ形をしている</b> ——
        取り除けば三人で足りる最小の役集合が 1 役で、その候補 4 役が<b>クリークを成す</b>。
        どれを外しても等しく解消するので、特定の一役を「四人目」と名指しすることはできない。
      </p>
      <ul>
        {over.map((p) => (
          <li key={p.id}>
            <Link href={`/play/${p.id}/`}>{p.ja}</Link>(χ = {p.chi.A_loose})
          </li>
        ))}
      </ul>
      <p>
        したがって目玉を組み替えた。<b>「三人で足りることを示す」から
        「三人に収まらない役を機械的に特定する」へ</b>。
      </p>

      <h2>対照 —— χ の小ささは役数の産物ではないか</h2>
      <p>
        役が 5 つしかなければ χ は高々 5 で、3 に収まっても不思議はない。
        これを排除しなければ何も主張していないことになる。
      </p>
      <p>
        そこで、発話の並びと場面の境界はそのままに、<b>役のラベルだけを篇内で無作為に置換した</b>
        偽の劇を作った(seed 20260902・2,000 回)。置換は発話総数・場面の数と大きさ・境界の位置・
        役の数・各役の発話回数をすべて保ち、<b>どの役がどの場面に集まるか</b>だけを壊す。
      </p>
      <div className="note">
        実測で χ ≤ 3 の悲劇は緩 28/34。一方、<b>偽の劇が 2,000 回のうち一度でも χ ≤ 3 に達した篇は
        5/34 しかない</b>。篇ごとの片側検定では厳 30/34・緩 29/34 で p &lt; 0.01。
        『アンティゴネ』は実測 3 に対し偽の劇の平均 8.06、
        『フェニキアの女たち』は実測 3 に対し 10.0 である。
        <br />
        <b>χ の小ささは役数でも発話数でも場面数でもなく、役の配置に由来する。</b>
      </div>

      <h2>方法の弱点</h2>
      <p>
        <b>合唱隊が語らない区間では退場を検出できない。</b>
        とくに合唱隊が登場する前のプロロゴスは丸ごと一場面に併合されるので、
        実際には入れ替わった役が同席しているように見える。
      </p>
      <p>
        この弱点は、独立の経路からも指摘された。45 篇 × 厳緩 = 90 組のうち
        <b>実測が偽の劇の平均を上回ったのは『<Link href="/play/tlg0085.tlg007/">エウメニデス</Link>』緩の 1 組だけ</b>で、
        まさに上の弱点を指摘していた篇である。実際そこで結ばれる四役
        (ピュティア・アポロン・オレステス・クリュタイムネストラの亡霊)は第 0 場面 ——
        プロロゴス —— に現れ、ピュティアは亡霊の登場前に退場している。
      </p>

      <h2>測らなかったこと</h2>
      <ul>
        <li>
          <b>作家間の語彙比較</b> —— 校訂者が作家と一対一なので、測れば校訂者を測ることになる
        </li>
        <li>
          <b>韻律・韻</b> —— <code>@rend</code> は校訂者ごとに 0.0%〜25.5% とばらけ、手がかりにならない
        </li>
        <li>
          <b>英訳</b> —— Perseus は 45 篇中 36 篇に英訳を持つが、χ は原文から導いている
        </li>
      </ul>

      <h2>素材に見つけた欠陥</h2>
      <ul>
        <li>
          『福の神』に行番号の破損が 2 件(<code>n=&quot;3933&quot;</code> は
          <code>393e</code> の誤植、<code>n=&quot;NaN&quot;</code> は 128)
        </li>
        <li>
          <code>&lt;speaker&gt;</code> を持たない発話が 3 件(『追跡者たち』203 行・
          『ペルシア人』200 行・『アガメムノン』83 行)。3 件とも直前話者の続きであることを
          行番号の連続で個別に確認して継承した
        </li>
        <li>共同発話が 2 篇 5 箇所 —— 「一発話 = 一話者」の前提が崩れる</li>
        <li>『縛られたプロメテウス』の 5 行で <code>@rend</code> に行番号が漏れている</li>
      </ul>
      <p style={{ color: "var(--ink-faint)", fontSize: ".85rem" }}>
        <code>data/raw</code> は原本のまま据え置き、補正は派生側の表で行っている。
      </p>
    </main>
  );
}
